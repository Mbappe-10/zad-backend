<?php

$origins = array_values(
    array_filter(
        array_map(
            static fn (string $origin): string => trim($origin),
            explode(
                ',',
                (string) env(
                    'CORS_ALLOWED_ORIGINS',
                    env(
                        'FRONTEND_URL',
                        'http://127.0.0.1:8080'
                    )
                )
            )
        )
    )
);

return [

    /*
    |--------------------------------------------------------------------------
    | المسارات التي يسمح لها باستخدام CORS
    |--------------------------------------------------------------------------
    */

    'paths' => [
        'api/*',
        'admin/*',
        'auth/*',
        'sanctum/csrf-cookie',
        'storage/*',
    ],

    /*
    |--------------------------------------------------------------------------
    | طرق الطلب المسموحة
    |--------------------------------------------------------------------------
    */

    'allowed_methods' => [
        '*',
    ],

    /*
    |--------------------------------------------------------------------------
    | عناوين الفرونت المسموحة
    |--------------------------------------------------------------------------
    */

    'allowed_origins' => $origins,

    'allowed_origins_patterns' => [],

    /*
    |--------------------------------------------------------------------------
    | الترويسات المسموحة
    |--------------------------------------------------------------------------
    */

    'allowed_headers' => [
        'Accept',
        'Authorization',
        'Content-Type',
        'Origin',
        'X-Requested-With',
        'X-XSRF-TOKEN',
        'X-CSRF-TOKEN',
    ],

    /*
    |--------------------------------------------------------------------------
    | الترويسات التي يسمح للمتصفح بقراءتها
    |--------------------------------------------------------------------------
    */

    'exposed_headers' => [],

    /*
    |--------------------------------------------------------------------------
    | مدة حفظ نتيجة Preflight
    |--------------------------------------------------------------------------
    */

    'max_age' => 86400,

    /*
    |--------------------------------------------------------------------------
    | السماح بالكوكيز والجلسات
    |--------------------------------------------------------------------------
    */

    'supports_credentials' => true,
];